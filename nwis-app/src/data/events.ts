// ─── Utility Functions ───

export function getEventsByWell(wellId: string): DrillingEvent[] {
  return EVENTS.filter(e => e.wellId === wellId);
}

export function getEventsByFormation(formationId: string): DrillingEvent[] {
  return EVENTS.filter(e => e.formationId === formationId);
}

export function getEventsByType(eventType: EventType): DrillingEvent[] {
  return EVENTS.filter(e => e.eventType === eventType);
}

export function getEventsByField(field: string): DrillingEvent[] {
  return EVENTS.filter(e => e.field === field);
}

export function getRecentEvents(count: number = 10): DrillingEvent[] {
  return [...EVENTS].sort((a, b) => new Date(b.timestamp).getTime() - new Date(a.timestamp).getTime()).slice(0, count);
}
